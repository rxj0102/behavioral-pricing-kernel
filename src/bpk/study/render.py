"""Write the generated parts of the README from results/real/metrics.json.

    python -m bpk.study.render           rewrite the generated blocks
    python -m bpk.study.render --check   exit 1 if the README is out of date

The verdict on each hypothesis is computed here from the rules written down in Amendment 3,
so the README cannot claim more than the numbers allow.
"""

# ruff: noqa: E501
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
MARK = "<!-- {name}:start (generated by python -m bpk.study.render, do not edit by hand) -->"
END = "<!-- {name}:end -->"
NAMES = {
    "none": "No risk adjustment",
    "crra": "CRRA",
    "habit": "Habit-style",
    "weight": "Probability weighting",
    "weight_sentiment": "Probability weighting with sentiment",
}
POINTS = ["P(fall of 20%+)", "10th percentile", "Median", "90th percentile", "P(below +20%)"]


def verdicts(m: dict[str, Any]) -> dict[str, tuple[bool, str]]:
    """Apply the decision rules of Amendment 3."""
    dm6, dm12 = m["dm"]["6m"], m["dm"]["12m"]
    beats_crra = dm6["weight vs crra"]["p_one_sided"] < 0.05
    beats_habit = dm6["weight vs habit"]["p_one_sided"] < 0.05
    both12 = all(dm12[k]["p_one_sided"] < 0.05 for k in ("weight vs crra", "weight vs habit"))
    h1 = beats_crra and beats_habit
    if h1:
        why1 = "Beats both benchmarks out of sample at 5 percent."
    elif beats_crra:
        why1 = "Beats CRRA out of sample but not the habit-style model at 5 percent"
        why1 += "; beats both at 12 months." if both12 else "."
    else:
        why1 = "Does not beat CRRA out of sample."
    c = m["h2"]["curvature"]
    h2 = (
        c["slope"] > 0
        and abs(c["t"]) > 1.96
        and min(c["slope_first_half"], c["slope_second_half"]) > 0
    )
    why2 = (
        "Slope positive, significant and stable across halves."
        if h2
        else ("Slope is negative" if c["slope"] <= 0 else "Slope is positive")
        + (" and" if abs(c["t"]) <= 1.96 else " but")
        + (" not significant." if abs(c["t"]) <= 1.96 else " unstable.")
    )
    h3m = m["h3"]
    key = h3m["comparisons"]["vrp_curvature vs vrp"]
    h3 = bool(h3m["run"]) and key["r2"] > 0 and key["p_value"] < 0.05 and h3m["placebo_p"] < 0.05
    why3 = (
        "Positive out-of-sample R squared, significant, and beats the placebo."
        if h3
        else "No significant out-of-sample gain over the variance risk premium."
    )
    h4m = m["h4"]
    h4 = h4m["sharpe"]["vrp_curvature"] > h4m["buy_hold_sharpe"] and h4m["dsr"] > 0.95
    why4 = "Beats buy and hold after costs." if h4 else "Does not beat buy and hold after costs."
    return {"H1": (h1, why1), "H2": (h2, why2), "H3": (h3, why3), "H4": (h4, why4)}


def pp(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}"


def robustness_sentence(rows: list[dict[str, Any]] | None) -> str:
    """One sentence on the post hoc physical density check, from physical_robustness.json."""
    if not rows:
        return ""
    n = len(rows)
    beats = sum(r["weight_vs_crra"]["t"] > 1.96 for r in rows)
    tails = sum(r["share_alpha_below_one"] > 0.5 for r in rows)
    if beats == n:
        raise SystemExit("robustness rows now all favour weighting; rewrite robustness_sentence()")
    return (
        f" A later check that was not pre-registered shows this rests on the assumed realistic "
        f"distribution: across {n} reasonable choices of it, weighting beats CRRA at 5 percent in only "
        f"{beats}, while the distortion still overweights tails on most dates in {tails} "
        f"([results/real/physical_robustness.md](results/real/physical_robustness.md))."
    )


def headline(m: dict[str, Any], rob: list[dict[str, Any]] | None = None) -> str:
    v = verdicts(m)
    s, f6 = m["sample"], m["fit"]["6m"]["models"]
    dm6, cu = m["dm"]["6m"], m["curvature"]
    best = min((k for k in f6 if k != "weight_sentiment"), key=lambda k: f6[k]["rmse_oos"])
    checks = {
        "probability weighting has the lowest out-of-sample error": best == "weight",
        "it also has the lowest error at 12 months": min(
            m["fit"]["12m"]["models"], key=lambda k: m["fit"]["12m"]["models"][k]["rmse_oos"]
        )
        == "weight",
        "it beats CRRA at 5 percent": dm6["weight vs crra"]["p_one_sided"] < 0.05,
        "it does not beat the habit-style model at 5 percent": dm6["weight vs habit"]["p_one_sided"]
        >= 0.05,
        "H2, H3 and H4 are not supported": not (v["H2"][0] or v["H3"][0] or v["H4"][0]),
        "alpha is below one on most dates": cu["share_below_one"] > 0.8,
    }
    failed = [k for k, ok in checks.items() if not ok]
    if failed:
        raise SystemExit(
            "The README summary no longer matches the results; rewrite headline() in "
            "src/bpk/study/render.py. Failed: " + "; ".join(failed)
        )
    h3 = m["h3"]["comparisons"]["vrp_curvature vs vrp"]
    return (
        f"**Answer, on {s['n_dates_6m']} real option-implied densities from {s['first_date'][:4]} to "
        f"{s['last_date'][:4]}: not by the tests set in advance.** All four pre-registered hypotheses fail. "
        f"One finding survives those tests. Probability weighting fits the gap between market-implied and realistic "
        f"probabilities better out of sample than standard risk aversion (average error "
        f"{pp(f6['weight']['rmse_oos'])} against {pp(f6['crra']['rmse_oos'])} percentage points, "
        f"t = {dm6['weight vs crra']['t']:.1f}), and the estimated distortion overweights tail events on "
        f"{pp(cu['share_below_one'], 0)}% of dates. But it does not clearly beat a habit-style benchmark "
        f"(p = {dm6['weight vs habit']['p_one_sided']:.2f}), so the first hypothesis fails its own "
        f"pre-registered test at the main horizon.{robustness_sentence(rob)} The distortion does not rise with investor sentiment "
        f"(t = {m['h2']['curvature']['t']:.1f}, wrong sign), it does not predict returns out of sample "
        f"(R squared gain {pp(h3['r2'])}%, p = {h3['p_value']:.2f}), and trading on it loses to buy and hold. "
        f"No model fits well in absolute terms: the best one still misses by {pp(f6[best]['rmse_oos'])} "
        f"percentage points of probability on average."
    )


def results(m: dict[str, Any]) -> str:
    v = verdicts(m)
    s = m["sample"]
    out: list[str] = []
    out += ["| Hypothesis | Pre-registered test | Verdict |", "|---|---|---|"]
    tests = {
        "H1": "Probability weighting beats CRRA and habit-style out of sample (Diebold-Mariano, 5%)",
        "H2": "Distortion rises with lagged sentiment, significant and stable in both halves",
        "H3": "Distortion predicts next month's return out of sample beyond the variance risk premium",
        "H4": "A timing strategy on that forecast beats buy and hold after costs",
    }
    for h, text in tests.items():
        ok, why = v[h]
        out.append(f"| {h} | {text} | **{'Supported' if ok else 'Not supported'}.** {why} |")
    out.append("")
    out.append(
        f"Sample: {s['n_dates_6m']} dates at 6 months and {s['n_dates_12m']} at 12 months, "
        f"{s['first_date']} to {s['last_date']}. Parameters are re-estimated each January on earlier "
        f"dates only; out of sample means {s['first_oos_year']} onward. Errors are root mean squared "
        f"gaps between model-implied and published risk-neutral probabilities at five points, in "
        f"percentage points."
    )
    for tenor in ("6m", "12m"):
        f = m["fit"][tenor]
        out += [
            "",
            f"**Model fit, {tenor[:-1]} month horizon** ({f['n_oos']} out-of-sample dates)",
            "",
        ]
        out += [
            "| Model | Parameters | In-sample error | Out-of-sample error | Full-sample estimate |",
            "|---|---|---|---|---|",
        ]
        for k, r in f["models"].items():
            est = ", ".join(f"{x:.2f}" for x in r["theta_full_sample"]) or "n/a"
            out.append(
                f"| {NAMES[k]} | {r['n_params']} | {pp(r['rmse_in_sample'])} | "
                f"{pp(r['rmse_oos'])} | {est} |"
            )
    out += [
        "",
        "Estimates are gamma for CRRA; gamma0, gamma1 for habit-style; gamma, alpha for "
        "probability weighting; gamma, alpha0, delta with sentiment. The sentiment model is "
        "scored on the dates with sentiment data, so its errors are not on the same sample.",
    ]
    out += [
        "",
        "**Diebold-Mariano tests on out-of-sample losses** (Newey-West, "
        f"{s['dm_lags']} lags; positive t favours the first model)",
        "",
        "| Comparison | Horizon | t | One-sided p | Dates |",
        "|---|---|---|---|---|",
    ]
    label = {
        "weight vs crra": "Probability weighting vs CRRA",
        "weight vs habit": "Probability weighting vs habit-style",
        "crra vs none": "CRRA vs no risk adjustment",
        "weight_sentiment vs weight": "Adding sentiment vs probability weighting",
    }
    for tenor in ("6m", "12m"):
        for k, r in m["dm"][tenor].items():
            out.append(
                f"| {label[k]} | {tenor[:-1]} months | {r['t']:.2f} | {r['p_one_sided']:.3f} | {r['n']} |"
            )
    out += [
        "",
        "**Where each model misses** (6 months, out of sample): mean model-implied minus "
        "published probability, percentage points",
        "",
        "| Model | " + " | ".join(POINTS) + " |",
        "|---|" + "---|" * 5,
    ]
    for k, g in m["gaps_oos_6m"].items():
        out.append(f"| {NAMES[k]} | " + " | ".join(f"{100 * x:+.1f}" for x in g) + " |")
    cu, rc = m["curvature"], m["reconstruction"]
    out += [
        "",
        f"**The distortion.** Estimated date by date, the Prelec parameter alpha has median "
        f"{cu['alpha_median']:.2f} (10th to 90th percentile {cu['alpha_p10']:.2f} to {cu['alpha_p90']:.2f}) "
        f"and is below one, meaning tails are overweighted, on {pp(cu['share_below_one'], 0)}% of dates. "
        f"The reconstructed pricing kernel rises somewhere between the 5th and 95th percentile on "
        f"{pp(cu['share_nonmonotone'], 0)}% of dates. The two-normal reconstruction reproduces the "
        f"published probabilities to within {pp(rc['max_gap_median'])} percentage points at the median date.",
    ]
    c, u = m["h2"]["curvature"], m["h2"]["upvar"]
    out += [
        "",
        f"**H2, sentiment.** Regressing month-end curvature (1 - alpha) on lagged Baker-Wurgler "
        f"sentiment over {c['n_months']} months ({m['h2']['first_month']} to {m['h2']['last_month']}) gives a slope "
        f"of {c['slope']:.3f} (Newey-West t = {c['t']:.2f}); {c['slope_first_half']:.3f} in the first half and "
        f"{c['slope_second_half']:.3f} in the second. High-sentiment months minus the rest: "
        f"{c['high_minus_rest']:.3f} (t = {c['high_minus_rest_t']:.2f}). The secondary measure, upward "
        f"variation of the log kernel, has slope {u['slope']:.3f} (t = {u['t']:.2f}).",
    ]
    h3 = m["h3"]
    out += [
        "",
        f"**H3, return prediction.** {h3['n_oos']} out-of-sample months ({h3['first_oos']} to "
        f"{h3['last_oos']}; the stated threshold was {h3['threshold']}).",
        "",
        "| Forecast | Benchmark | Out-of-sample R squared | Clark-West p |",
        "|---|---|---|---|",
    ]
    lab = {
        "vrp_curvature vs vrp": ("Variance risk premium + curvature", "Variance risk premium"),
        "vrp_curvature vs mean": ("Variance risk premium + curvature", "Historical mean"),
        "curvature vs mean": ("Curvature", "Historical mean"),
        "vrp vs mean": ("Variance risk premium", "Historical mean"),
    }
    for k, r in h3["comparisons"].items():
        out.append(f"| {lab[k][0]} | {lab[k][1]} | {pp(r['r2'])}% | {r['p_value']:.2f} |")
    out += [
        "",
        f"Placebo: {pp(h3['placebo_p'], 1)}% of 1000 shuffles of the curvature series do at least as "
        f"well as the real one in the first row.",
    ]
    h4 = m["h4"]
    out += [
        "",
        f"**H4, timing.** Over {h4['n_months']} months the strategy has a Sharpe ratio of "
        f"{h4['sharpe']['vrp_curvature']:.2f} after costs against {h4['buy_hold_sharpe']:.2f} for buy and hold "
        f"(t of the difference in mean return {h4['minus_buy_hold_t']:.2f}), with an average market weight of "
        f"{h4['mean_weight']:.2f} and turnover of {h4['turnover_per_year']:.1f} times a year. Its Deflated "
        f"Sharpe Ratio is {h4['dsr']:.2f} with {h4['n_trials']} logged trials; that statistic asks whether the "
        f"Sharpe ratio is above {h4['hurdle_annual']:.2f}, not whether it beats holding the market.",
    ]
    return "\n".join(out)


def fill(text: str, name: str, body: str) -> str:
    start, end = MARK.format(name=name), END.format(name=name)
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "real" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    rob_path = ROOT / "results" / "real" / "physical_robustness.json"
    rob = json.loads(rob_path.read_text()) if rob_path.exists() else None
    new = fill(fill(text, "headline", headline(m, rob)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python -m bpk.study.render")
            sys.exit(1)
        print("README matches results/real/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
